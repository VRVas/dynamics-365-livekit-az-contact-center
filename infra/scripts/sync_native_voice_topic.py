"""Regenerate the shareable, credential-free winning controller snapshot."""

import argparse
import stage_native_media_topic as topics


OUTPUT = topics.ROOT / "apps/voice/dynamics/native-speech-turn-pilot.topic.yaml"
CRM_OUTPUT = topics.ROOT / "apps/voice/dynamics/native-speech-turn-crm-pilot.topic.yaml"
SUPERVISION_OUTPUT = topics.ROOT / "apps/voice/dynamics/native-supervision-pilot.topic.yaml"


def generated(*, crm_case_context=False, supervision=False):
    return "# Generated by infra/scripts/sync_native_voice_topic.py; do not edit directly.\r\n" + topics.render_speech_turn_pilot(
        topics.load_topic(topics.TEMPLATE.read_text()), crm_case_context=crm_case_context, supervision=supervision,
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--crm-case-context", action="store_true", help="Generate the opt-in CaseNumber controller; requires its global variable.")
    parser.add_argument("--supervision", action="store_true", help="Generate the isolated opt-in native supervision contract snapshot.")
    args = parser.parse_args()
    if args.supervision and args.crm_case_context:
        parser.error("Use the supervision setup kit to preserve a deployed CaseNumber controller; the shareable supervision snapshot is standalone.")
    output = SUPERVISION_OUTPUT if args.supervision else CRM_OUTPUT if args.crm_case_context else OUTPUT
    expected = generated(crm_case_context=args.crm_case_context, supervision=args.supervision).encode()
    if args.check:
        if not output.is_file() or output.read_bytes() != expected:
            raise SystemExit("The native speech-turn snapshot is stale; run this script without --check.")
        print("Native speech-turn snapshot matches the renderer; no credentials required.")
    else:
        output.write_bytes(expected)
        print(f"Generated {output.relative_to(topics.ROOT)} with placeholders only.")


if __name__ == "__main__":
    main()
