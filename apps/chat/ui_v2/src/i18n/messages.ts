export type MessageKey = keyof typeof arabic;

export function translate(locale: Locale, text: string, values: Record<string, string | number> = {}): string {
  const known = (key: string): key is MessageKey => Object.hasOwn(arabic, key);
  let result: string = locale === 'ar' && known(text) ? arabic[text] : text;
  if (locale === 'ar' && text.startsWith('Could not reach the voice backend at ')) {
    result = arabic['Could not reach the voice backend.'];
  }
  for (const [key, value] of Object.entries(values)) {
    result = result.replaceAll(`{${key}}`, String(value));
  }
  return result;
}
